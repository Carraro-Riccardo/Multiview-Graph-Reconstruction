def _code_view_support(all_views_dets: list) -> dict:
    valid_views = 0
    counts = defaultdict(int)
    for dets in all_views_dets:
        topo_codes = {
            d["code"] for d in dets
            if d["code"] not in DIAMETER_CODES and d["code"] in COMPONENT_INFO
        }
        if not topo_codes:
            continue
        valid_views += 1
        for code in topo_codes:
            counts[code] += 1
    if valid_views == 0:
        return {}
    return {code: cnt / valid_views for code, cnt in counts.items()}


def _hypothesis_context_score(hyp_code: int, neighbor_codes: list,
                              type_consensus: dict, view_support: dict) -> float:
    if hyp_code not in COMPONENT_INFO:
        return -np.inf

    sat = DEGREE_SATURATION.get(hyp_code, 0.5)
    score = view_support.get(hyp_code, 0.0) * 1.5
    score += sat * 2.0

    pair_scores = []
    for nb in neighbor_codes:
        pair = tuple(sorted((hyp_code, nb)))
        pair_scores.append(
            type_consensus.get(pair, 0.0) * 3.0 + cooc_score(hyp_code, nb) * 2.0
        )
    if pair_scores:
        score += sum(pair_scores) / len(pair_scores)

    triplet_bonus = 0.0
    bridge_pair_bonus = 0.0
    for i in range(len(neighbor_codes)):
        for j in range(i + 1, len(neighbor_codes)):
            a, b = neighbor_codes[i], neighbor_codes[j]
            key = (min(a, b), hyp_code, max(a, b))
            ts = TRIPLET_COUNTS.get(key, 0) / _MAX_TRIPLET
            triplet_bonus = max(triplet_bonus, ts)
            bridge_pair_bonus += ts
    score += triplet_bonus * 6.0
    score += bridge_pair_bonus * 2.0

    mixed_neighbors = set(neighbor_codes[:2])
    if len(mixed_neighbors) >= 2:
        # In a mixed local context, bridge-like components should win over
        # terminal-ish ones, and duplicating one neighbor type is suspicious.
        if sat < 0.5:
            score -= 1.5
        if hyp_code in mixed_neighbors:
            score -= 2.5
        if triplet_bonus == 0.0:
            score -= 1.0

    return score


def consolidate_best_view_codes(best_dets: list, all_views_dets: list,
                                type_consensus: dict, debug_dirs: dict | None = None) -> list:
    """
    Correzione conservativa dei codici della best view usando supporto dalle altre viste.
    Non aggiunge/rimuove nodi: prova solo a rilabelare detection sospette quando
    il contesto locale e il supporto multi-vista indicano un tipo diverso.
    """
    dets = copy.deepcopy(best_dets)
    topo_indices = [
        i for i, d in enumerate(dets)
        if d["code"] not in DIAMETER_CODES and d["code"] in COMPONENT_INFO
    ]
    if len(topo_indices) < 3:
        return dets

    pts = np.array([[dets[i]["cx"], dets[i]["cy"]] for i in topo_indices])
    D = cdist(pts, pts)
    np.fill_diagonal(D, np.inf)

    view_support = _code_view_support(all_views_dets)
    observed_codes = sorted({
        d["code"]
        for view in all_views_dets
        for d in view
        if d["code"] not in DIAMETER_CODES and d["code"] in COMPONENT_INFO
    })

    debug_payload = {
        "view_support": {str(k): v for k, v in sorted(view_support.items())},
        "observed_codes": observed_codes,
        "events": [],
    }

    for local_i, det_idx in enumerate(topo_indices):
        current = dets[det_idx]["code"]
        current_val = get_valence(current)
        current_support = view_support.get(current, 0.0)
        neighbor_order = np.argsort(D[local_i])[:3]
        neighbor_codes = [dets[topo_indices[j]]["code"] for j in neighbor_order]
        current_score = _hypothesis_context_score(
            current, neighbor_codes, type_consensus, view_support
        )

        print(
            f"    [ViewFuseCheck] idx={det_idx} code={current} {get_name(current)} "
            f"support={current_support:.2f} neighbors={neighbor_codes} score={current_score:.2f}"
        )

        candidate_records = []
        best_alt = None
        best_score = current_score
        for alt in observed_codes:
            if alt == current:
                continue
            if get_valence(alt) != current_val:
                continue
            alt_support = view_support.get(alt, 0.0)
            if alt_support <= current_support and alt_support == 0.0:
                continue

            alt_score = _hypothesis_context_score(
                alt, neighbor_codes, type_consensus, view_support
            )
            pair_alt = np.mean([
                type_consensus.get(tuple(sorted((alt, nb))), 0.0)
                for nb in neighbor_codes
            ]) if neighbor_codes else 0.0
            candidate_records.append({
                "code": alt,
                "name": get_name(alt),
                "view_support": alt_support,
                "score": alt_score,
                "pair_mean": pair_alt,
            })
            if alt_score > best_score + 1.5:
                best_score = alt_score
                best_alt = alt

        candidate_records.sort(key=lambda item: (-item["score"], -item["view_support"], item["code"]))
        for cand in candidate_records[:5]:
            print(
                f"      alt {cand['code']} {cand['name']} | support={cand['view_support']:.2f} "
                f"pair_mean={cand['pair_mean']:.2f} score={cand['score']:.2f}"
            )

        event = {
            "det_index": det_idx,
            "current_code": current,
            "current_name": get_name(current),
            "current_support": current_support,
            "neighbor_codes": neighbor_codes,
            "current_score": current_score,
            "alternatives": candidate_records[:8],
        }

        if current_support >= 0.45:
            event["action"] = "keep_supported"
            debug_payload["events"].append(event)
            continue

        if best_alt is None:
            event["action"] = "keep_no_better_alt"
            debug_payload["events"].append(event)
            continue

        pair_current = np.mean([
            type_consensus.get(tuple(sorted((current, nb))), 0.0)
            for nb in neighbor_codes
        ]) if neighbor_codes else 0.0
        pair_alt = np.mean([
            type_consensus.get(tuple(sorted((best_alt, nb))), 0.0)
            for nb in neighbor_codes
        ]) if neighbor_codes else 0.0

        if pair_alt < pair_current + 0.1 and view_support.get(best_alt, 0.0) <= current_support:
            event["action"] = "keep_pair_guard"
            event["best_alt"] = best_alt
            event["best_alt_name"] = get_name(best_alt)
            event["best_alt_score"] = best_score
            debug_payload["events"].append(event)
            continue

        print(
            f"    [ViewFuse] idx={det_idx} {get_name(current)}({current}) -> "
            f"{get_name(best_alt)}({best_alt}) | "
            f"views {current_support:.2f}->{view_support.get(best_alt, 0.0):.2f} | "
            f"ctx={neighbor_codes} | score {current_score:.2f}->{best_score:.2f}"
        )
        dets[det_idx]["code"] = best_alt
        if "name" in dets[det_idx]:
            dets[det_idx]["name"] = get_name(best_alt)
        if "max_degree" in dets[det_idx]:
            dets[det_idx]["max_degree"] = get_valence(best_alt)

        event["action"] = "relabel"
        event["best_alt"] = best_alt
        event["best_alt_name"] = get_name(best_alt)
        event["best_alt_score"] = best_score
        debug_payload["events"].append(event)

    if debug_dirs is not None:
        save_consolidation(debug_dirs, debug_payload)

    return dets

