def edge_allowed(ca: int, cb: int) -> bool:
    if ca == cb and ca != 255:
        return False
    if get_valence(ca) == 1 and get_valence(cb) == 1:
        return False
    if tuple(sorted((ca, cb))) in FORBIDDEN_PAIRS:
        return False
    return True


def edge_creates_bad_pattern(G: nx.Graph, u: str, v: str) -> bool:
    ca = G.nodes[u]["code"]
    cb = G.nodes[v]["code"]
    for w in G.neighbors(u):
        if G.nodes[w]["code"] == cb and cb == ca:
            return True
    for w in G.neighbors(v):
        if G.nodes[w]["code"] == ca and ca == cb:
            return True
    BAD_MIDDLE = {95, 207}
    if cb in BAD_MIDDLE:
        if ca in [G.nodes[w]["code"] for w in G.neighbors(v)]:
            return True
    if ca in BAD_MIDDLE:
        if cb in [G.nodes[w]["code"] for w in G.neighbors(u)]:
            return True
    return False


