def build_per_view_type_edges(dets: list, k: int = K_NEIGHBORS) -> set:
    """
    Da una singola vista, costruisce il grafo KNN sui nodi topologici e
    restituisce l'insieme delle coppie di tipi (code_a, code_b) connesse.
    """
    topo = [d for d in dets
            if d["code"] not in DIAMETER_CODES and d["code"] in COMPONENT_INFO]
    if len(topo) < 2:
        return set()

    pts   = np.array([[d["cx"], d["cy"]] for d in topo])
    codes = [d["code"] for d in topo]
    D     = cdist(pts, pts)
    np.fill_diagonal(D, np.inf)

    edges = set()
    for i, ca in enumerate(codes):
        va = get_valence(ca)
        for j in np.argsort(D[i])[:max(va, k)]:
            cb = codes[j]
            if edge_allowed(ca, cb):
                edges.add(tuple(sorted((ca, cb))))
    return edges


def aggregate_type_consensus(all_views_dets: list, k: int = K_NEIGHBORS) -> dict:
    """
    Aggrega i voti di adiacenza tra tipi di componenti su tutte le viste.
    Ritorna {(ca, cb): frazione_di_viste} per ogni coppia di tipi osservata.

    INTERPRETAZIONE: se in 5/6 viste "Tee FL" appare vicino a "Saracinesca",
    quella coppia quasi certamente ÃƒÆ’Ã‚Â¨ connessa fisicamente. La prospettiva
    cambia le distanze pixel ma NON la topologia di adiacenza.
    """
    valid_views = 0
    pair_counts = defaultdict(int)

    for dets in all_views_dets:
        edges = build_per_view_type_edges(dets, k)
        if edges:
            valid_views += 1
            for pair in edges:
                pair_counts[pair] += 1

    if valid_views == 0:
        return {}
    return {pair: count / valid_views for pair, count in pair_counts.items()}


