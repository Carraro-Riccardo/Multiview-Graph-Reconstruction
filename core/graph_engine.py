def break_cycles(G: nx.Graph, pos_2d: dict, cutoff: float) -> nx.Graph:
    """
    Rende il grafo aciclico (albero) rimuovendo iterativamente l'arco
    con score peggiore in ogni ciclo trovato.

    Score dell'arco (per decidere quale rimuovere):
      - mv_score     (peso alto: consenso multi-vista)
      - confirm_ratio (se disponibile)
      - triplet_score (compatibilitÃƒÆ’Ã‚Â  contestuale)
      - penalitÃƒÆ’Ã‚Â  per archi forzati o di recovery

    Garantisce connettivitÃƒÆ’Ã‚Â : rimuovere un arco di un ciclo non disconnette
    mai il grafo per definizione. Non isola nodi: verifica grado > 1.
    """
    G = copy.deepcopy(G)

    def _score(u, v):
        d  = G[u][v]
        sc = d.get("mv_score", 0.0) * 2.0
        sc += d.get("confirm_ratio", 0.0) * 0.5
        sc += d.get("triplet_score", 0.0) * 0.8
        sc += cooc_score(G.nodes[u]["code"], G.nodes[v]["code"]) * 0.3
        if d.get("forced",   False): sc -= 0.5
        if d.get("recovery", False): sc -= 0.3
        return sc

    for _ in range(G.number_of_edges()):
        try:
            cycle = nx.find_cycle(G)
        except nx.NetworkXNoCycle:
            break

        sorted_edges = sorted(cycle, key=lambda e: _score(e[0], e[1]))

        removed = False
        for eu, ev, *_ in sorted_edges:
            if G.degree(eu) > 1 and G.degree(ev) > 1:
                print(f"    [CycleBreak] rimosso {eu}ÃƒÂ¢Ã¢â‚¬Â Ã¢â‚¬Â{ev} "
                      f"(score={_score(eu, ev):.3f})")
                G.remove_edge(eu, ev)
                removed = True
                break

        if not removed:
            print(f"    [CycleBreak] ciclo non spezzabile senza isolare nodi")
            break

    return G


