def _mutual_rank_score(D: np.ndarray, dets: list, i: int, j: int) -> float:
    """
    Score di rango mutuo: quanto i e j sono vicendevolmente vicini
    tra i propri vicini validi. Cattura la "naturalitÃƒÆ’Ã‚Â " di un collegamento
    indipendentemente dalla scala assoluta delle distanze.
      ri = rango di j tra i vicini validi di i (0 = il piÃƒÆ’Ã‚Â¹ vicino)
      rj = rango di i tra i vicini validi di j (0 = il piÃƒÆ’Ã‚Â¹ vicino)
      score = 1 / (1 + ri + rj)   ÃƒÂ¢Ã¢â‚¬Â Ã¢â‚¬â„¢ max 1.0 se entrambi vicini reciproci
    """
    n = len(dets)
    ca, cb = dets[i]["code"], dets[j]["code"]

    neighbors_of_i = sorted(
        (D[i, k], k) for k in range(n)
        if k != i and edge_allowed(ca, dets[k]["code"])
    )
    ri = next((r for r, (_, k) in enumerate(neighbors_of_i) if k == j), 99)

    neighbors_of_j = sorted(
        (D[j, k], k) for k in range(n)
        if k != j and edge_allowed(cb, dets[k]["code"])
    )
    rj = next((r for r, (_, k) in enumerate(neighbors_of_j) if k == i), 99)

    return 1.0 / (1.0 + ri + rj)


def _build_local_candidate_pairs(D: np.ndarray, dets: list, type_consensus: dict,
                                 cutoff: float,
                                 top_k: int = LOCAL_TOP_K,
                                 rank_k: int = LOCAL_RANK_K,
                                 hard_max_factor: float = HARD_MAX_DIST_FACTOR) -> tuple:
    """
    Costruisce un insieme di archi candidati strettamente locali.

    Filosofia:
      - la geometria decide chi puo' competere
      - consenso multi-vista e priors semantici servono solo a riordinare
      - i nodi a valenza 3/4 ottengono un po' piu' elasticita' locale
    """
    n = len(dets)
    if n < 2:
        return [], {}

    hard_max_dist = cutoff * hard_max_factor
    neighbor_lists = {}
    candidate_pairs = set()

    for i in range(n):
        ca = dets[i]["code"]
        neighbors = []
        for j in range(n):
            if i == j:
                continue
            cb = dets[j]["code"]
            if not edge_allowed(ca, cb):
                continue
            dist = D[i, j]
            pair = tuple(sorted((ca, cb)))
            allow_hub_rescue = (
                _is_hub_preferred_neighbor(ca, cb)
                and type_consensus.get(pair, 0.0) >= HUB_RESCUE_MIN_MV
                and dist <= cutoff * HUB_RESCUE_DIST_FACTOR
            )
            if dist > hard_max_dist and not allow_hub_rescue:
                continue
            neighbors.append((dist, j))
        neighbors.sort()
        neighbor_lists[i] = neighbors

    candidate_sources = defaultdict(set)

    for i in range(n):
        ca = dets[i]["code"]
        ranked_neighbors = neighbor_lists[i]
        local_top_k = top_k + (HUB_MIN_EXTRA_K if get_valence(ca) >= 3 else 0)
        for _, j in ranked_neighbors[:local_top_k]:
            cb = dets[j]["code"]
            reverse_rank_k = rank_k + (HUB_RANK_EXTRA if max(get_valence(ca), get_valence(cb)) >= 3 else 0)
            reverse_top = {idx for _, idx in neighbor_lists[j][:reverse_rank_k]}
            if i not in reverse_top:
                continue
            pair_ij = (min(i, j), max(i, j))
            candidate_pairs.add(pair_ij)
            candidate_sources[pair_ij].add("mutual")

    for i in range(n):
        ca = dets[i]["code"]
        if get_valence(ca) < 3:
            continue
        preferred = []
        for dist, j in neighbor_lists[i]:
            cb = dets[j]["code"]
            pair = tuple(sorted((ca, cb)))
            if not _is_hub_preferred_neighbor(ca, cb):
                continue
            if dist > cutoff * HUB_RESCUE_DIST_FACTOR:
                continue
            if type_consensus.get(pair, 0.0) < HUB_RESCUE_MIN_MV:
                continue
            preferred.append((dist, j))
        for _, j in preferred[:get_valence(ca) + 2]:
            pair_ij = (min(i, j), max(i, j))
            candidate_pairs.add(pair_ij)
            candidate_sources[pair_ij].add("hub_mv")

    for i in range(n):
        if any(i in pair for pair in candidate_pairs):
            continue
        if neighbor_lists[i]:
            _, j = neighbor_lists[i][0]
            pair_ij = (min(i, j), max(i, j))
            candidate_pairs.add(pair_ij)
            candidate_sources[pair_ij].add("fallback")

    pair_features = {}
    for i, j in sorted(candidate_pairs):
        ca, cb = dets[i]["code"], dets[j]["code"]
        pair = tuple(sorted((ca, cb)))
        dist = D[i, j]
        dist_norm = dist / max(cutoff, 1e-9)
        mr = _mutual_rank_score(D, dets, i, j)
        mv = type_consensus.get(pair, 0.0)
        cooc = cooc_score(ca, cb)

        hub_bonus = 0.0
        if get_valence(ca) >= 3 or get_valence(cb) >= 3:
            if ca in HIGH_VALENCE_CODES and cb in HIGH_VALENCE_CODES:
                hub_bonus += 1.25
            if ca == 15 or cb == 15:
                hub_bonus += 1.5
            if get_valence(ca) >= 3 and get_valence(cb) >= 3:
                hub_bonus += 0.75

        hub_penalty = _hub_penalty(ca, cb)
        score = (
            mr * 3.5
            + mv * 3.0
            + cooc * 2.0
            + hub_bonus
            - hub_penalty
            - (dist_norm ** 2) * 4.0
        )
        pair_features[(i, j)] = {
            "pair": pair,
            "dist": dist,
            "dist_norm": dist_norm,
            "mutual_rank": mr,
            "mv": mv,
            "cooc": cooc,
            "hub_bonus": hub_bonus,
            "hub_penalty": hub_penalty,
            "source": "+".join(sorted(candidate_sources.get((i, j), {"unknown"}))),
            "score": score,
        }

    return sorted(pair_features), pair_features

def _connect_components_soft(G: nx.Graph, nodes: list, dets: list, D: np.ndarray,
                              type_consensus: dict, cutoff: float,
                              min_plausibility: float = SOFT_CONNECT_MIN_SCORE) -> nx.Graph:
    """
    Connettivita' opzionale post-ILP: collega componenti disconnesse solo se
    esiste un arco locale sufficientemente plausibile.
    Non viola la valenza fisica e non usa rescue edge a lunga distanza.
    """
    n = len(dets)
    candidate_pairs, pair_features = _build_local_candidate_pairs(
        D, dets, type_consensus, cutoff
    )

    for _ in range(n):
        components = list(nx.connected_components(G))
        if len(components) <= 1:
            break

        comp_of = {nid: ci for ci, comp in enumerate(components) for nid in comp}
        best_score, best_pair = -np.inf, None

        for i, j in candidate_pairs:
            if comp_of[nodes[i]] == comp_of[nodes[j]]:
                continue
            ca, cb = dets[i]["code"], dets[j]["code"]
            if G.degree(nodes[i]) >= get_valence(ca):
                continue
            if G.degree(nodes[j]) >= get_valence(cb):
                continue
            feats = pair_features[(i, j)]
            if feats["score"] < min_plausibility:
                continue
            if feats["score"] > best_score:
                best_score, best_pair = feats["score"], (i, j)

        if best_pair is None:
            print(f"    [Soft-Connect] nessun arco plausibile "
                  f"(soglia={min_plausibility:.2f}) - grafo rimane disconnesso")
            break

        i, j = best_pair
        best_u, best_v = nodes[i], nodes[j]
        best_ca, best_cb = dets[i]["code"], dets[j]["code"]
        feats = pair_features[(i, j)]
        pair = tuple(sorted((best_ca, best_cb)))
        mv_score = type_consensus.get(pair, 0.0)
        supported_reconnect = (mv_score >= 0.5 and feats["cooc"] >= 0.5)
        G.add_edge(best_u, best_v, dist=feats["dist"],
                   forced=True, recovery=False,
                   supported_reconnect=supported_reconnect,
                   cooc=feats["cooc"],
                   mv_score=mv_score,
                   triplet_score=0.0,
                   mutual_rank=feats["mutual_rank"],
                   plausibility=best_score)
        print(f"    [Soft-Connect] {best_u}->{best_v} "
              f"(plaus={best_score:.3f}, dist={feats['dist']:.3f})")

    return G

def _postprocess_tree_edges(active_edges: list, dets: list, pair_features: dict,
                            nodes: list) -> list:
    """
    Piccolo rewiring post-ILP per correggere incoerenze globali attorno ai tee/croci.
    Sostituisce archi hub->vicini sfavoriti con archi hub->vicini preferiti se
    il nuovo collegamento e' supportato dal candidate set locale e migliora il
    punteggio semantico del ciclo risultante.
    """
    if not active_edges:
        return active_edges

    T = nx.Graph()
    T.add_nodes_from(range(len(dets)))
    T.add_edges_from(active_edges)

    def edge_key(a: int, b: int) -> tuple:
        return (min(a, b), max(a, b))

    def score_edge(a: int, b: int) -> float:
        return pair_features.get(edge_key(a, b), {}).get("score", -np.inf)

    for _ in range(len(dets)):
        improved = False
        deg = dict(T.degree())

        for hub in range(len(dets)):
            ch = dets[hub]["code"]
            if get_valence(ch) < 3:
                continue

            bad_neighbors = [nb for nb in T.neighbors(hub)
                             if _hub_penalty(ch, dets[nb]["code"]) > 0]
            if not bad_neighbors:
                continue

            candidates = []
            for j in range(len(dets)):
                if j == hub or T.has_edge(hub, j):
                    continue
                cj = dets[j]["code"]
                if not _is_hub_preferred_neighbor(ch, cj):
                    continue
                ek = edge_key(hub, j)
                if ek not in pair_features:
                    continue
                candidates.append((score_edge(hub, j), j))

            candidates.sort(reverse=True)
            for new_score, j in candidates:
                path = nx.shortest_path(T, hub, j)
                path_edges = [edge_key(path[k], path[k + 1]) for k in range(len(path) - 1)]
                best_swap = None

                for rem_u, rem_v in path_edges:
                    rem_score = score_edge(rem_u, rem_v)
                    rem_penalty = _hub_penalty(dets[rem_u]["code"], dets[rem_v]["code"])
                    gain = new_score - rem_score + rem_penalty * 1.5

                    impacted = {hub, j, rem_u, rem_v}
                    valid = True
                    for node_idx in impacted:
                        new_deg = deg[node_idx]
                        if node_idx in {hub, j}:
                            new_deg += 1
                        if node_idx in {rem_u, rem_v}:
                            new_deg -= 1
                        if new_deg > get_valence(dets[node_idx]["code"]):
                            valid = False
                            break
                    if not valid:
                        continue

                    if best_swap is None or gain > best_swap[0]:
                        best_swap = (gain, rem_u, rem_v)

                if best_swap is None or best_swap[0] <= 0.5:
                    continue

                _, rem_u, rem_v = best_swap
                T.add_edge(hub, j)
                T.remove_edge(rem_u, rem_v)
                print(f"    [PostHub] {nodes[hub]}->{nodes[j]} aggiunto | rimosso {nodes[rem_u]}->{nodes[rem_v]}")
                improved = True
                break

            if improved:
                break

        if not improved:
            break

    return sorted(edge_key(u, v) for u, v in T.edges())

def build_graph_ilp_soft(best_dets: list, type_consensus: dict,
                         debug_dirs: dict | None = None, best_view_path=None) -> tuple:
    """
    ILP geometry-first con connettivita' e aciclicita' implicita da spanning tree.

    Rispetto alla versione soft precedente:
      - i candidati restano strettamente locali
      - la soluzione finale deve essere connessa
      - il grafo ha esattamente n-1 archi, quindi e' aciclico
      - il vincolo di grado usa la valenza fisica hard del componente
    """
    try:
        import pulp
    except ImportError:
        print("  [ILP-soft] pulp non installato (pip install pulp) - fallback greedy")
        return build_graph_consensus_first(best_dets, type_consensus)

    dets = [d for d in best_dets
            if d["code"] not in DIAMETER_CODES and d["code"] in COMPONENT_INFO]
    if len(dets) < 2:
        return build_graph_consensus_first(best_dets, type_consensus)

    n = len(dets)
    pts = np.array([[d["cx"], d["cy"]] for d in dets])
    D = cdist(pts, pts)
    np.fill_diagonal(D, np.inf)
    cutoff = compute_dist_cutoff(pts)

    code_counter = defaultdict(int)
    nodes = []
    for d in dets:
        nid = f"{d['code']}#{code_counter[d['code']]}"
        code_counter[d["code"]] += 1
        nodes.append(nid)

    valid_pairs, pair_features = _build_local_candidate_pairs(D, dets, type_consensus, cutoff)
    if not valid_pairs:
        return build_graph_consensus_first(best_dets, type_consensus)

    print(f"  [CandidateSet] local_pairs={len(valid_pairs)} cutoff={cutoff:.3f}")
    ranked_pairs = sorted(pair_features.items(), key=lambda item: (-item[1]["score"], item[1]["dist"]))
    for rank, ((i, j), feats) in enumerate(ranked_pairs[:12], start=1):
        print(
            f"    [Cand#{rank}] {nodes[i]}->{nodes[j]} "
            f"score={feats['score']:.3f} dist={feats['dist']:.3f} "
            f"mv={feats['mv']:.2f} cooc={feats['cooc']:.2f} "
            f"mr={feats['mutual_rank']:.3f} src={feats['source']}"
        )
    if debug_dirs is not None:
        save_json(
            debug_dirs["candidates"] / "candidate_pairs.json",
            [
                {
                    "pair": [i, j],
                    "nodes": [nodes[i], nodes[j]],
                    "codes": [dets[i]["code"], dets[j]["code"]],
                    **feats,
                }
                for (i, j), feats in ranked_pairs
            ],
        )
        if best_view_path is not None:
            save_candidate_snapshot(
                debug_dirs,
                best_view_path,
                dets,
                pair_features,
                filename="candidate_edges_all.png",
                title="All local candidate edges",
            )

    pair_score = {pair: feats["score"] for pair, feats in pair_features.items()}

    triplet_bonus: dict = defaultdict(float)
    for i in range(n):
        ca = dets[i]["code"]
        neighbors_j = [j for j in range(n)
                       if j != i and (min(i, j), max(i, j)) in pair_score]
        for ja in range(len(neighbors_j)):
            for jb in range(ja + 1, len(neighbors_j)):
                j, k = neighbors_j[ja], neighbors_j[jb]
                cb, cc = dets[j]["code"], dets[k]["code"]
                key = (min(cb, cc), ca, max(cb, cc))
                ts = TRIPLET_COUNTS.get(key, 0) / _MAX_TRIPLET
                if ts > 0:
                    e1 = (min(i, j), max(i, j))
                    e2 = (min(i, k), max(i, k))
                    triplet_bonus[e1] += ts * 2.0
                    triplet_bonus[e2] += ts * 2.0

    for e, bonus in triplet_bonus.items():
        if e in pair_score:
            pair_score[e] += bonus

    if debug_dirs is not None:
        save_json(
            debug_dirs["candidates"] / "pair_scores_after_triplets.json",
            [
                {
                    "pair": [i, j],
                    "nodes": [nodes[i], nodes[j]],
                    "codes": [dets[i]["code"], dets[j]["code"]],
                    "score": pair_score[(i, j)],
                    "triplet_bonus": triplet_bonus.get((i, j), 0.0),
                    **pair_features[(i, j)],
                }
                for (i, j) in sorted(pair_score)
            ],
        )

    for i, d in enumerate(dets):
        if get_valence(d["code"]) < 3:
            continue
        ranked = []
        for j in range(n):
            if i == j:
                continue
            e = (min(i, j), max(i, j))
            if e not in pair_features:
                continue
            feats = pair_features[e]
            ranked.append((pair_score[e], j, feats))
        ranked.sort(key=lambda item: (-item[0], item[2]["dist"]))
        print(f"    [HubDebug] {nodes[i]} code={d['code']} val={get_valence(d['code'])} candidates={len(ranked)}")
        for rank, (sc, j, feats) in enumerate(ranked[:6], start=1):
            print(
                f"      #{rank} -> {nodes[j]} code={dets[j]['code']} "
                f"sc={sc:.3f} mv={feats['mv']:.2f} mr={feats['mutual_rank']:.3f} "
                f"cooc={feats['cooc']:.2f} hub=+{feats['hub_bonus']:.2f}/-{feats['hub_penalty']:.2f} "
                f"dist={feats['dist']:.3f} src={feats['source']}"
            )

    prob = pulp.LpProblem("graph_ilp_local_tree", pulp.LpMaximize)
    x = {(i, j): pulp.LpVariable(f"x_{i}_{j}", cat="Binary") for (i, j) in valid_pairs}

    def get_x(i, j):
        return x.get((min(i, j), max(i, j)))

    prob += pulp.lpSum(pair_score[e] * x[e] for e in valid_pairs)

    for i in range(n):
        incident = [get_x(i, j) for j in range(n) if j != i and get_x(i, j) is not None]
        if incident:
            val = get_valence(dets[i]["code"])
            prob += pulp.lpSum(incident) <= val, f"max_deg_{i}"
            if val >= 3 and len(incident) >= val:
                prob += pulp.lpSum(incident) >= val, f"hub_full_deg_{i}"
            else:
                prob += pulp.lpSum(incident) >= 1, f"min_deg_{i}"

    prob += pulp.lpSum(x[e] for e in valid_pairs) == n - 1, "tree_size"

    active_edges = []
    for iteration in range(n + 1):
        status = prob.solve(pulp.PULP_CBC_CMD(msg=0))
        if status != 1:
            print(f"  [ILP-soft] infeasibile (iter={iteration}) - fallback greedy")
            return build_graph_consensus_first(best_dets, type_consensus)

        active_edges = [(i, j) for (i, j) in valid_pairs if (pulp.value(x[(i, j)]) or 0) > 0.5]

        tmp = nx.Graph()
        tmp.add_nodes_from(range(n))
        tmp.add_edges_from(active_edges)
        components = list(nx.connected_components(tmp))
        print(
            f"    [ILPIter] iter={iteration} status={status} "
            f"edges={len(active_edges)} comps={len(components)}"
        )
        if debug_dirs is not None:
            save_solver_summary(
                debug_dirs,
                {
                    "iteration": iteration,
                    "status": int(status),
                    "active_edges": [
                        {
                            "pair": [i, j],
                            "nodes": [nodes[i], nodes[j]],
                            "codes": [dets[i]["code"], dets[j]["code"]],
                            "score": pair_score[(i, j)],
                        }
                        for (i, j) in active_edges
                    ],
                    "components": [sorted(nodes[idx] for idx in comp) for comp in components],
                },
                name=f"solver_iter_{iteration}.json",
            )
        if len(components) == 1:
            break

        for ci, comp in enumerate(components):
            comp_set = set(comp)
            others = set(range(n)) - comp_set
            crossing = [(i, j) for (i, j) in valid_pairs
                        if (i in comp_set and j in others) or (j in comp_set and i in others)]
            if crossing:
                cname = f"conn_{iteration}_{ci}"
                if cname not in prob.constraints:
                    prob += (pulp.lpSum(x[e] for e in crossing) >= 1, cname)
    else:
        print("  [ILP-soft] connettivita' non raggiunta - fallback greedy")
        return build_graph_consensus_first(best_dets, type_consensus)

    active_edges = _postprocess_tree_edges(active_edges, dets, pair_features, nodes)
    if debug_dirs is not None:
        save_solver_summary(
            debug_dirs,
            {
                "selected_edges": [
                    {
                        "pair": [i, j],
                        "nodes": [nodes[i], nodes[j]],
                        "codes": [dets[i]["code"], dets[j]["code"]],
                        "score": pair_score[(i, j)],
                        "features": pair_features[(i, j)],
                    }
                    for (i, j) in active_edges
                ]
            },
            name="solver_selected_edges.json",
        )
        if best_view_path is not None:
            save_candidate_snapshot(
                debug_dirs,
                best_view_path,
                dets,
                pair_features,
                selected_pairs=active_edges,
                filename="candidate_edges_selected.png",
                title="Selected tree edges",
            )

    G = nx.Graph()
    for i, nid in enumerate(nodes):
        code = dets[i]["code"]
        G.add_node(
            nid,
            code=code,
            name=get_name(code),
            valence=get_valence(code),
            eff_valence=effective_valence(code),
            cx=dets[i]["cx"],
            cy=dets[i]["cy"],
        )

    for (i, j) in active_edges:
        u, v = nodes[i], nodes[j]
        feats = pair_features[(i, j)]
        G.add_edge(
            u, v,
            dist=feats["dist"],
            recovery=False,
            forced=False,
            cooc=feats["cooc"],
            mv_score=feats["mv"],
            triplet_score=triplet_bonus.get((i, j), 0.0) / 2.0,
            mutual_rank=feats["mutual_rank"],
            local_score=pair_score[(i, j)],
        )

    n_comp = nx.number_connected_components(G)
    print(f"  [ILP-soft] {len(active_edges)} edge | {'connesso' if n_comp == 1 else f'{n_comp} componenti'}")
    for i, d in enumerate(dets):
        if get_valence(d["code"]) < 3:
            continue
        neighbors = [nodes[j] for j in range(n) if i != j and (min(i, j), max(i, j)) in active_edges]
        print(f"    [HubChosen] {nodes[i]} deg={len(neighbors)}/{get_valence(d['code'])} -> {', '.join(neighbors) or '-'}")

    pos_2d = {nodes[i]: (dets[i]["cx"], dets[i]["cy"]) for i in range(n)}
    return G, pos_2d, cutoff
def confirm_edges_multivista(G: nx.Graph, all_views_dets: list,
                              best_view_idx: int, debug_dirs: dict | None = None) -> nx.Graph:
    """
    Annota ogni arco con quante viste alternative mostrano quella coppia
    di tipi come vicini KNN. Usato solo per la visualizzazione.
    """
    n_other = len(all_views_dets) - 1
    edge_payload = []
    for u, v in G.edges():
        cu, cv = G.nodes[u]["code"], G.nodes[v]["code"]
        confirms = 0
        supporting_views = []
        view_checks = []
        for idx, dets in enumerate(all_views_dets):
            if idx == best_view_idx:
                continue
            topo = [d for d in dets if d["code"] not in DIAMETER_CODES]
            if len(topo) < 2:
                view_checks.append({
                    "view_index": idx,
                    "view_support": False,
                    "reason": "too_few_topological_nodes",
                    "neighbor_codes": [],
                })
                continue
            pts = np.array([[d["cx"], d["cy"]] for d in topo])
            codes = [d["code"] for d in topo]
            Dm = cdist(pts, pts)
            np.fill_diagonal(Dm, np.inf)
            hit = False
            neighbor_codes = []
            for i, ca in enumerate(codes):
                if ca != cu:
                    continue
                nn_idx = np.argsort(Dm[i])[:K_NEIGHBORS]
                neighbor_codes = [codes[j] for j in nn_idx]
                if cv in neighbor_codes:
                    confirms += 1
                    supporting_views.append(idx)
                    hit = True
                    break
            view_checks.append({
                "view_index": idx,
                "view_support": hit,
                "neighbor_codes": neighbor_codes,
            })
        ratio = confirms / max(n_other, 1)
        G.edges[u, v]["confirmations"] = confirms
        G.edges[u, v]["confirm_ratio"] = ratio
        edge_payload.append({
            "edge": [u, v],
            "codes": [cu, cv],
            "confirmations": confirms,
            "confirm_ratio": ratio,
            "supporting_views": supporting_views,
            "per_view": view_checks,
        })
        print(
            f"  [MVEdge] {u}<->{v} codes=({cu},{cv}) confirms={confirms}/{max(n_other, 1)} "
            f"ratio={ratio:.2f} views={supporting_views}"
        )
    if debug_dirs is not None:
        save_json(debug_dirs["multiview"] / "edge_confirmations.json", edge_payload)
    return G

