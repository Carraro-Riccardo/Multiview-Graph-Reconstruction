def compute_dist_cutoff(pts: np.ndarray, multiplier: float = DIST_MULTIPLIER) -> float:
    if len(pts) < 2:
        return np.inf
    D = cdist(pts, pts)
    np.fill_diagonal(D, np.inf)
    return float(np.median(D.min(axis=1)) * multiplier)


def effective_cutoff(base_cutoff: float, ca: int, cb: int, mv: float = 0.0) -> float:
    """
    Raggio di ricerca adattivo. Un alto consenso multi-vista espande il raggio
    per catturare coppie fisicamente connesse che appaiono lontane a causa
    della prospettiva in questa vista specifica.
    """
    raw    = cooc_raw(ca, cb)
    cutoff = base_cutoff
    if raw >= 10:  cutoff *= 2.0
    elif raw >= 5: cutoff *= 1.5
    elif raw >= 3: cutoff *= 1.25
    if mv >= 0.75:   cutoff = max(cutoff, base_cutoff * 3.0)
    elif mv >= 0.5:  cutoff = max(cutoff, base_cutoff * 2.0)
    elif mv >= 0.25: cutoff = max(cutoff, base_cutoff * 1.5)
    return cutoff


